const std = @import("std");
pub fn fourcc(comptime tag: []const u8) u32 {
  if (tag.len != 4) @panic("");
  return (@as(u32, tag[0])) | (@as(u32, tag[1]) <<  8) | (@as(u32, tag[2]) << 16) | (@as(u32, tag[3]) << 24);
}
pub fn BitFlags(comptime F: type) type {
  const A = std.meta.Int(.unsigned, @typeInfo(F).Enum.fields.len);
  return struct {
    a: A = 0, const B = @This();
    pub fn empty() B { return .{ .a = 0 }; }
    pub fn full() B { return .{ .a = ~@as(A, 0) }; }
    pub fn set(b: *B, f: F) void { b.a |= mask(f); }
    pub fn unset(b: *B, f: F) void { b.a &= ~mask(f); }
    pub fn toggle(b: *B, f: F) void { b.a ^= mask(f); }
    pub fn has(b: B, f: F) bool { return (b.a & mask(f)) != 0; }
    pub fn clear(b: *B) void { b.a = 0; }
    pub fn toInt(b: B) A { return b.a; }
    pub fn fromInt(v: A) B { return .{ .a = v }; }
    fn mask(f: F) A { return @as(A, 1) << @intFromEnum(f); }
  };
}
