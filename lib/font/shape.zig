    var res = FeatureSet{ .flags = [_]u64{0} ** ((@intFromEnum(FeatureId.count) + 63) / 64) };
    for (features) |f| {
      const val = @intFromEnum(f);
      res.flags[val / 64] |= (@as(u64, 1) << @as(u6, @intCast(val % 64)));
    }
    return res;
  }
};

